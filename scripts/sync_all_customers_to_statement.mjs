const db = getFirestore(app);

async function syncAllCustomersToStatement() {
  const [custSnap, invSnap, rcptSnap, retSnap, jeSnap, coaSnap] = await Promise.all([
    getDocs(collection(db, 'companies/idham-main/customers')),
    getDocs(collection(db, 'companies/idham-main/salesInvoices')),
    getDocs(collection(db, 'companies/idham-main/receipts')),
    getDocs(collection(db, 'companies/idham-main/salesReturns')),
    getDocs(collection(db, 'companies/idham-main/journalEntries')),
    getDocs(collection(db, 'companies/idham-main/chartOfAccounts'))
  ]);

  const customers = custSnap.docs.map(d => ({ id: d.id, ...d.data() }));
  const invoices = invSnap.docs.map(d => ({ id: d.id, ...d.data() })).filter(i => i.status !== 'cancelled');
  const receipts = rcptSnap.docs.map(d => ({ id: d.id, ...d.data() })).filter(r => r.status !== 'cancelled' && (!r.entityType || r.entityType === 'customer'));
  const returns = retSnap.docs.map(d => ({ id: d.id, ...d.data() })).filter(r => r.status !== 'cancelled' && r.status !== 'void');
  const journalEntries = jeSnap.docs.map(d => ({ id: d.id, ...d.data() })).filter(j => j.status !== 'cancelled' && !j.isReversed);
  const coa = coaSnap.docs.map(d => ({ id: d.id, ...d.data() }));

  console.log(`Auditing and syncing all ${customers.length} customer balances to statement...`);

  let updatedCount = 0;

  for (const cust of customers) {
    const custId = cust.id;
    const custName = (cust.name || '').trim().toLowerCase();
    const storedBalance = parseFloat(cust.balance || 0);
    const openingBalance = parseFloat(cust.openingBalance || 0);

    const matchedCoa = coa.filter(a => a.sourceEntityId === custId);
    const matchedAccCodes = new Set(matchedCoa.map(a => a.code).filter(Boolean));
    const matchedAccIds = new Set(matchedCoa.map(a => a.id).filter(Boolean));

    let totalDr = 0;
    let totalCr = 0;

    // Invoices (Debit)
    invoices.filter(i => i.customerId === custId).forEach(inv => {
      totalDr += parseFloat(inv.totalWithVat || inv.total || 0);
    });

    // Receipts (Credit)
    receipts.filter(r => r.targetId === custId || r.customerId === custId).forEach(rcpt => {
      totalCr += parseFloat(rcpt.amount || 0);
    });

    // Returns (Credit)
    returns.filter(r => r.customerId === custId).forEach(ret => {
      totalCr += parseFloat(ret.totalWithVat || ret.total || 0);
    });

    // Manual JEs
    journalEntries.forEach(je => {
      const st = (je.sourceType || '').toLowerCase();
      const rt = (je.refType || '').toLowerCase();
      const desc = (je.description || '').toLowerCase();

      const isAutoGenerated = 
        st === 'salesinvoice' || st === 'sales' || st === 'receipt' || st === 'salesreturn' || 
        st === 'sales_return' || st === 'salescogs' || st === 'cogs' || st === 'salesreturncogs' || 
        st === 'salesinvoice_cogs' || st === 'collection' || st === 'expense' || st === 'supplierpayment' ||
        rt.includes('sales') || rt.includes('receipt') || rt.includes('invoice') || rt.includes('return') ||
        desc.includes('مبيعات') || desc.includes('فاتورة') || desc.includes('سند قبض') || 
        desc.includes('مرتجع') || desc.includes('إشعار دائن') || desc.includes('تصفية');

      if (isAutoGenerated) return;

      (je.lines || []).forEach(line => {
        const lAccId = line.accountId;
        const lAccCode = line.accountCode;
        const lAccName = (line.accountName || '').trim().toLowerCase();

        const isMatch = (lAccId && matchedAccIds.has(lAccId)) ||
                        (lAccCode && matchedAccCodes.has(lAccCode)) ||
                        (custName && lAccName && (lAccName === custName || lAccName.includes(custName) || custName.includes(lAccName)));

        if (isMatch) {
          const dAmt = parseFloat(line.debit || 0);
          const cAmt = parseFloat(line.credit || 0);
          if (dAmt === 0 && cAmt === 0) return;
          totalDr += dAmt;
          totalCr += cAmt;
        }
      });
    });

    const statementBalance = Math.round((openingBalance + totalDr - totalCr) * 100) / 100;
    if (Math.abs(storedBalance - statementBalance) > 0.01) {
      console.log(`Syncing ${cust.name}: Old Stored=${storedBalance} -> New Statement Balance=${statementBalance}`);
      await updateDoc(doc(db, `companies/idham-main/customers`, custId), {
        balance: statementBalance
      });
      updatedCount++;
    }
  }

  console.log(`\nSuccessfully synced ${updatedCount} customers to exact Statement of Account balance.`);
}

syncAllCustomersToStatement().then(() => process.exit(0)).catch(e => { console.error(e); process.exit(1); });
