function parseFields(fields = {}) {
  const r = {};
  for (const [k, v] of Object.entries(fields)) {
    if      (v.stringValue  !== undefined) r[k] = v.stringValue;
    else if (v.doubleValue  !== undefined) r[k] = v.doubleValue;
    else if (v.integerValue !== undefined) r[k] = parseInt(v.integerValue);
    else if (v.booleanValue !== undefined) r[k] = v.booleanValue;
    else if (v.arrayValue)                r[k] = (v.arrayValue.values||[]).map(x=>parseFields(x.mapValue?.fields||{}));
    else if (v.mapValue)                  r[k] = parseFields(v.mapValue.fields||{});
    else r[k] = null;
  }
  return r;
}

async function getAllPages(collPath) {
  let allDocs = [];
  let pageToken = null;
  do {
    let url = `${BASE}/${collPath}?key=${API_KEY}&pageSize=300`;
    if (pageToken) url += `&pageToken=${encodeURIComponent(pageToken)}`;
    const resp = await fetch(url);
    const data = await resp.json();
    if (data.error) {
      console.error(`Error fetching ${collPath}:`, data.error);
      return [];
    }
    const docs = (data.documents || []).map(d => ({
      id: d.name.split('/').pop(),
      ...parseFields(d.fields || {})
    }));
    allDocs = allDocs.concat(docs);
    pageToken = data.nextPageToken || null;
  } while (pageToken);
  return allDocs;
}

async function patchDoc(docPath, updateMaskFields, fieldsObj) {
  const mask = updateMaskFields.map(f => `updateMask.fieldPaths=${encodeURIComponent(f)}`).join('&');
  const url = `${BASE}/${docPath}?key=${API_KEY}&${mask}`;

  const firestoreFields = {};
  for (const [k, v] of Object.entries(fieldsObj)) {
    if (typeof v === 'number') {
      firestoreFields[k] = { doubleValue: v };
    } else if (typeof v === 'string') {
      firestoreFields[k] = { stringValue: v };
    } else if (typeof v === 'boolean') {
      firestoreFields[k] = { booleanValue: v };
    }
  }

  const resp = await fetch(url, {
    method: 'PATCH',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ fields: firestoreFields })
  });
  return resp.json();
}

async function run() {
  const compId = "idham-main";
  const [customers, invoices, receipts, returns, jes, coa] = await Promise.all([
    getAllPages(`companies/${compId}/customers`),
    getAllPages(`companies/${compId}/salesInvoices`),
    getAllPages(`companies/${compId}/receipts`),
    getAllPages(`companies/${compId}/salesReturns`),
    getAllPages(`companies/${compId}/journalEntries`),
    getAllPages(`companies/${compId}/chartOfAccounts`)
  ]);

  console.log(`Starting sync for ${customers.length} customers...`);

  let updatedCount = 0;

  for (const c of customers) {
    const custId = c.id;
    const custName = (c.name || "").trim().toLowerCase();

    const matchedAccCodes = new Set();
    const matchedAccIds = new Set();
    let matchedCOAAccount = null;
    coa.forEach(d => {
      if (d.sourceEntityId === custId) {
        matchedCOAAccount = d;
        matchedAccIds.add(d.id);
        if (d.code) matchedAccCodes.add(d.code);
      }
    });

    const cInvs = invoices.filter(i => (i.customerId === custId || (i.customerName && i.customerName.trim().toLowerCase() === custName)) && i.status !== 'cancelled');
    const cRcpts = receipts.filter(r => (r.targetId === custId || r.customerId === custId || (r.customerName && r.customerName.trim().toLowerCase() === custName)) && r.status !== 'cancelled');
    const cRets = returns.filter(r => (r.customerId === custId || (r.customerName && r.customerName.trim().toLowerCase() === custName)) && r.status !== 'cancelled' && r.status !== 'void');

    let debit = 0;
    let credit = 0;

    cInvs.forEach(inv => {
      debit += parseFloat(inv.totalWithVat || inv.total || 0);
    });

    cRcpts.forEach(rcpt => {
      credit += parseFloat(rcpt.amount || 0);
    });

    cRets.forEach(ret => {
      credit += parseFloat(ret.totalWithVat || ret.total || 0);
    });

    jes.forEach(je => {
      if (je.status === "cancelled" || je.isReversed) return;
      const st = (je.sourceType || "").toLowerCase();
      const rt = (je.refType || "").toLowerCase();
      const desc = (je.description || "").toLowerCase();

      const isAutoGenerated = 
        st === "salesinvoice" || st === "sales" || st === "receipt" || st === "salesreturn" || 
        st === "sales_return" || st === "salescogs" || st === "cogs" || st === "salesreturncogs" || 
        st === "salesinvoice_cogs" || st === "collection" || st === "expense" || st === "supplierpayment" ||
        rt.includes("sales") || rt.includes("receipt") || rt.includes("invoice") || rt.includes("return") ||
        desc.includes("مبيعات") || desc.includes("فاتورة") || desc.includes("سند قبض") || 
        desc.includes("مرتجع") || desc.includes("إشعار دائن") || desc.includes("تصفية");

      if (isAutoGenerated) return;

      (je.lines || []).forEach(line => {
        const lAccId = line.accountId;
        const lAccCode = line.accountCode;
        const lAccName = (line.accountName || "").trim().toLowerCase();

        const isMatch = (lAccId && matchedAccIds.has(lAccId)) ||
                        (lAccCode && matchedAccCodes.has(lAccCode)) ||
                        (custName && lAccName && lAccName === custName);

        if (isMatch) {
          debit += parseFloat(line.debit || 0);
          credit += parseFloat(line.credit || 0);
        }
      });
    });

    const openBal = parseFloat(c.openingBalance || 0);
    const calculatedBalance = Math.round((openBal + debit - credit) * 100) / 100;
    const storedBalance = Math.round(Number(c.balance || 0) * 100) / 100;

    if (Math.abs(storedBalance - calculatedBalance) > 0.05) {
      console.log(`Updating ${c.name} (${c.code || c.id}): Stored ${storedBalance} -> New ${calculatedBalance}`);
      await patchDoc(`companies/${compId}/customers/${c.id}`, ['balance', 'currentBalance'], {
        balance: calculatedBalance,
        currentBalance: calculatedBalance
      });

      if (matchedCOAAccount) {
        await patchDoc(`companies/${compId}/chartOfAccounts/${matchedCOAAccount.id}`, ['balance', 'currentBalance'], {
          balance: calculatedBalance,
          currentBalance: calculatedBalance
        });
      }
      updatedCount++;
    }
  }

  console.log(`\nSuccessfully synchronized ${updatedCount} customer balances in Firestore.`);
}

run().catch(console.error);
